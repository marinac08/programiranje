class SSO {
    struct heap { //long
        char* arr=nullptr;  //8
        short size=0;       //2
        short cap=0;        //2
                            //4 buffer

        heap() = default;
        void konst(const char* o) {
            const short os = static_cast<short>(strlen(o));
            if (this->cap<os) {
                this->size=os;
                this->cap=this->size;
                this->arr=new char[this->cap+1];
                strcpy(this->arr, o);
            }
            else {
                this->size=os;
                strcpy(this->arr, o);
                //the rest of the array can have garbage, but it's divide by '\0'
            }
        }
        ~heap() {
            if (arr!= reinterpret_cast<char*>(0xcafe)) delete[] arr;
            this->arr=nullptr;
        }
        void destrukt() {
            if (arr!= reinterpret_cast<char*>(0xcafe) && arr!=nullptr) delete[] arr;
            this->arr=nullptr;
        }
        const heap& operator+(const char* o) {
            if (!o || o[0]=='\0') return *this;
            short add_len=static_cast<short>(strlen(o));
            short S=size+add_len;
            if (cap<S) {
                char* arr2=new char[S+1];
                for (short i=0; i<size; i++) arr2[i]=arr[i];
                for (short j=0; j<add_len; j++) arr2[size+j]=o[j];
                arr2[S]='\0';
                delete[] arr;
                arr=arr2;
                size=S;
                cap=S;
            }
            else {
                for (short j=0; j<add_len; j++) arr[size+j]=o[j];
                arr[S]='\0';
                size=S;
            }
            return *this;
        }
    };

    struct local { //short
        short x;        //2
        char arr[14];   //14
                        //0 buffer

        local() = default;
        void konst(const char* o) {
            if (static_cast<short>(strlen(o))>=14) {
                cout << "\neh?\n";
                return;
            }
            this->x=-13570;
            strcpy(this->arr,o);
        }
        ~local() = default;

        const local& operator+(const char* o) {
            short i=static_cast<short>(strlen(arr));
            short add=static_cast<short>(strlen(o));
            for (short j=0; j<add; j++) arr[i+j]=o[j];
            arr[i+add] = '\0';
            return *this;
        }

    };
    union S{
        heap h{};
        local l;
        S() = default;
        ~S() {}
    };
    S s;
    bool is_heap() const {
        if (s.l.x==-13570) return false;
        return true;
    }

public:
    SSO() {
        s.l.x = -13570;
        s.l.arr[0] = '\0';
    }
    SSO(const char* o) {
        if (!o) o="";
        if (strlen(o)<14) {
            s.l.x=-13570;
            //cout << static_cast<const void*>(s.h.arr) << '\n';
            strcpy(s.l.arr, o);
        }
        else {
            s.h.konst(o);
            // cout << static_cast<const void*>(s.h.arr) << '\n';
            // cout << s.l.x << '\n';
        }
    }

    ~SSO() {
        if (is_heap()) s.h.destrukt();
    }
    SSO(const SSO& o){
        if (o.is_heap()) {
            s.h.konst(o.s.h.arr);

        }
        else {
            this->s.l.x=-13570;
            strcpy(this->s.l.arr, o.s.l.arr);
        }
    }
    SSO& operator=(const SSO& o) {
        if (this==&o) return *this;
        this->~SSO();
        new (this) SSO(o);
        return *this;
    }
    short getSize() const {
        if (is_heap()) return s.h.size;
        return static_cast<short>(strlen(s.l.arr));
    }
    short getCap() const {
        if (is_heap()) return s.h.cap;
        return 14;
    }
    char& operator[](short p) {
        if (is_heap()) return s.h.arr[p];
        return s.l.arr[p];
    }
    SSO& operator+(const char* o) {
        if (!o || o[0]=='\0') return *this;
        const short S=getSize()+static_cast<short>(strlen(o));
        if (this->is_heap())
            s.h+o;
        else { //short
            if (S<14) {
                s.l+o;
            }
            else { //go to heap
                heap h2;
                h2+s.l.arr;
                h2+o;
                s.h.cap=h2.cap;
                s.h.size=h2.size;
                s.h.arr=h2.arr;
                h2.arr = nullptr;
            }
        }
        return *this;
    }
};


